#!/usr/bin/env python3
"""Writes or checks Source/DSP/Render/BlepKernel.h, the band-limited impulse
every board's level steps are rendered with (Render/StepBuffer.h).

A sound chip's output is piecewise constant: a list of (time, level) steps.
A step at fractional time f, band-limited to the host rate, is the integral of
a band-limited impulse placed at f. StepBuffer adds the impulse's samples to a
difference buffer and integrates it, so this table is that impulse, sampled
at every tap offset for each of kPhases fractional positions.

The impulse is a Kaiser-windowed sinc with its cutoff at half the host rate
(fc = 0.5), so phase 0 is a unit impulse: a step on a sample boundary is a
plain step. Its 32-sample window gives a transition band from about 0.4 to
0.6 of the host rate: content above 0.6 x rate is removed by the window's
stopband, and what lies between 0.5 and 0.6 folds into 0.4 to 0.5 attenuated
by the transition (above 19.2 kHz at 48 kHz). Tests/BoardTests.cpp measures
the table's passband and stopband independently.

Each phase is scaled to sum to exactly 2**kUnitBits, so a step integrates to
its exact level with no drift however many steps are added: the rounding
remainder goes to the phase's largest tap. Pure standard-library Python
(the Bessel function is its series), so every machine writes the same table.

  generate_blep.py --write Source/DSP/Render/BlepKernel.h
  generate_blep.py --check Source/DSP/Render/BlepKernel.h
"""

import argparse
import math
import sys

HALF_WIDTH = 16          # taps either side of the centre
TAPS = 2 * HALF_WIDTH + 1
PHASE_BITS = 8
PHASES = 1 << PHASE_BITS
UNIT_BITS = 20
CUTOFF = 0.5             # of the host rate
BETA = 10.0              # Kaiser shape: about 100 dB stopband for this width


def bessel_i0(x):
    total, term, k = 1.0, 1.0, 1
    while True:
        term *= (x / (2.0 * k)) ** 2
        total += term
        if term < 1e-17 * total:
            return total
        k += 1


def impulse(t):
    """The continuous band-limited impulse at t samples from its centre."""
    if abs(t) >= HALF_WIDTH:
        return 0.0
    x = 2.0 * CUTOFF * t
    sinc = 1.0 if t == 0.0 else math.sin(math.pi * x) / (math.pi * x)
    window = bessel_i0(BETA * math.sqrt(1.0 - (t / HALF_WIDTH) ** 2)) / bessel_i0(BETA)
    return 2.0 * CUTOFF * sinc * window


def table():
    unit = 1 << UNIT_BITS
    rows = []
    for phase in range(PHASES + 1):
        f = phase / PHASES
        # Tap j sits at sample base + j; the impulse's centre is at
        # base + HALF_WIDTH + f.
        values = [impulse(j - HALF_WIDTH - f) for j in range(TAPS)]
        total = sum(values)
        taps = [int(round(v / total * unit)) for v in values]
        taps[max(range(TAPS), key=lambda j: abs(values[j]))] += unit - sum(taps)
        rows.append(taps)
    return rows


def header():
    lines = [
        "#pragma once",
        "",
        "// Generated by Tools/generate_blep.py; do not edit. The band-limited",
        "// impulse for Render/StepBuffer.h: a Kaiser-windowed sinc (cutoff half the",
        f"// host rate, beta {BETA}, {TAPS} taps), sampled at {PHASES} + 1 fractional",
        f"// positions, each row summing to exactly 2^{UNIT_BITS}.",
        "",
        "#include <cstdint>",
        "",
        "namespace protocodus::reboot::blep {",
        "",
        f"constexpr int kTaps = {TAPS};",
        f"constexpr int kDelay = {HALF_WIDTH};",
        f"constexpr int kPhaseBits = {PHASE_BITS};",
        f"constexpr int kPhases = {PHASES};",
        f"constexpr int kUnitBits = {UNIT_BITS};",
        "",
        "constexpr std::int32_t kTable[kPhases + 1][kTaps] = {",
    ]
    for row in table():
        lines.append("    { " + ", ".join(str(v) for v in row) + " },")
    lines += ["};", "", "} // namespace protocodus::reboot::blep", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", metavar="PATH")
    group.add_argument("--check", metavar="PATH")
    args = parser.parse_args()
    text = header()
    if args.write:
        with open(args.write, "w", newline="\n") as f:
            f.write(text)
        return 0
    with open(args.check, newline="") as f:
        if f.read() != text:
            print(f"{args.check} differs from what Tools/generate_blep.py writes", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
