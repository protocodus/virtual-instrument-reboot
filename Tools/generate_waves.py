#!/usr/bin/env python3
"""Writes Source/DSP/Driver/Waves.h: the playing layer's own waves.

The wave channels play whatever a sound driver loads into their RAM. These
are ours, drawn from harmonic series (not taken from any game or driver):
32 samples of 4 bits for the handheld's wave channel and the Namco 163, 64 of
6 bits for the disk unit. Each wave is scaled so its lowest and highest
points use the whole range, then rounded to the nearest step.

  python3 Tools/generate_waves.py --write Source/DSP/Driver/Waves.h
  python3 Tools/generate_waves.py --check Source/DSP/Driver/Waves.h
"""

import argparse
import math
import sys

# name, [(harmonic, amplitude, phase in turns)]; "square" and friends are
# drawn directly so their edges are exact.
WAVES = [
    ("Sine", [(1, 1.0, 0.0)]),
    ("Triangle", "triangle"),
    ("Saw", "saw"),
    ("Square", "square"),
    ("Pulse 25", "pulse25"),
    ("Organ", [(1, 1.0, 0.0), (2, 0.7, 0.0), (4, 0.45, 0.0), (8, 0.2, 0.0)]),
    ("Hollow", [(1, 1.0, 0.0), (3, 0.6, 0.0), (5, 0.35, 0.0), (7, 0.2, 0.0)]),
    ("Reed", [(1, 1.0, 0.0), (2, 0.5, 0.25), (3, 0.6, 0.0), (5, 0.4, 0.25), (6, 0.3, 0.0)]),
]

# The disk unit's modulation table: a sine in its 3-bit step codes
# (0 +0, 1 +1, 2 +2, 3 +4, 5 -4, 6 -2, 7 -1; 4 resets, never used here),
# chosen so the accumulated counter follows one sine cycle over 32 steps.
MOD_STEPS = [0, 1, 2, 4, -4, -2, -1]
MOD_CODES = {0: 0, 1: 1, 2: 2, 4: 3, -4: 5, -2: 6, -1: 7}


def shape_value(shape, t):
    if shape == "triangle":
        return 1.0 - 4.0 * abs(t - 0.5)
    if shape == "saw":
        return 2.0 * t - 1.0
    if shape == "square":
        return 1.0 if t < 0.5 else -1.0
    if shape == "pulse25":
        return 1.0 if t < 0.25 else -1.0
    raise ValueError(shape)


def draw(spec, length, top):
    points = []
    for i in range(length):
        t = i / length
        if isinstance(spec, str):
            points.append(shape_value(spec, t))
        else:
            points.append(sum(a * math.sin(2 * math.pi * (k * t + p)) for k, a, p in spec))
    low, high = min(points), max(points)
    return [int(math.floor((v - low) / (high - low) * top + 0.5)) for v in points]


def mod_table():
    # Steps whose running sum follows 16 * sin over 32 entries, greedily.
    table, level = [], 0
    for i in range(32):
        target = round(16 * math.sin(2 * math.pi * (i + 1) / 32))
        step = min(MOD_STEPS, key=lambda s: abs(level + s - target))
        level += step
        table.append(MOD_CODES[step])
    return table


def render():
    out = []
    out.append("#pragma once")
    out.append("")
    out.append("// Generated by Tools/generate_waves.py; do not edit. The playing layer's")
    out.append("// own waves for the wave channels (ours: harmonic series, scaled to each")
    out.append("// chip's full range and rounded), and the disk unit's modulation table.")
    out.append("")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace protocodus::reboot {")
    out.append("")
    out.append(f"constexpr int kWaveCount = {len(WAVES)};")
    out.append("")
    out.append("struct Wave32 {")
    out.append("    const char* name;")
    out.append("    std::uint8_t samples[32];   // 4 bits each")
    out.append("    std::uint8_t packed[16];    // two a byte, the first in the high nibble")
    out.append("};")
    out.append("")
    out.append("constexpr Wave32 kWaves[kWaveCount] = {")
    for name, spec in WAVES:
        s = draw(spec, 32, 15)
        packed = [(s[2 * i] << 4) | s[2 * i + 1] for i in range(16)]
        out.append(f'    {{ "{name}",')
        out.append("      { " + ", ".join(str(v) for v in s) + " },")
        out.append("      { " + ", ".join(f"0x{v:02X}" for v in packed) + " } },")
    out.append("};")
    out.append("")
    out.append("// 64 samples of 6 bits, for the disk unit's wave RAM.")
    out.append("constexpr std::uint8_t kWaves64[kWaveCount][64] = {")
    for name, spec in WAVES:
        s = draw(spec, 64, 63)
        out.append("    { " + ", ".join(str(v) for v in s) + " },")
    out.append("};")
    out.append("")
    out.append("// The disk unit's 32 modulation step codes: one sine cycle.")
    out.append("constexpr std::uint8_t kModTable[32] = { " + ", ".join(str(v) for v in mod_table()) + " };")
    out.append("")
    out.append("} // namespace protocodus::reboot")
    out.append("")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write")
    group.add_argument("--check")
    args = parser.parse_args()
    text = render()
    if args.write:
        with open(args.write, "w", newline="\n") as f:
            f.write(text)
        return 0
    with open(args.check, newline="") as f:
        if f.read() != text:
            print(f"{args.check} differs from Tools/generate_waves.py", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
