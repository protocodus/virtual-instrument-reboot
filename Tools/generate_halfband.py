#!/usr/bin/env python3
"""Writes or checks Source/DSP/Render/HalfbandKernel.h, the filter each 2:1
stage of the oversampling decimator uses (Render/Decimator.h).

With oversampling the boards render at 2, 4 or 8 times the host rate, and a
chain of 2:1 stages brings the sum back down. Each stage is the same linear
phase halfband: a Kaiser-windowed sinc with its cutoff at a quarter of the
stage's input rate, so every other tap but the centre is zero and the
centre is exactly 0.5.

Its 67 taps (beta 10) give a passband to 0.2 and a stopband from 0.3 of the
stage's input rate, at least 98 dB down: at the last stage, at 48 kHz, flat to
19.2 kHz, and what folds back lands above 19.2 kHz. The stages before it see
the same band far inside their passband. Tests/BoardTests.cpp measures the
kernel's passband and stopband independently.

The half length (33 taps) is chosen so the decimator delays the output by a
whole number of host samples at every factor: each stage keeps the odd input
samples, a delay of (33 - 1) / 2 = 16 of its output samples, so 8x adds
16 / 4 + 16 / 2 + 16 = 28 host samples and the step kernel's 16 samples at
8x are 2 more (Engine::LatencySamples). Pure standard-library Python, so
every machine writes the same coefficients.

  generate_halfband.py --write Source/DSP/Render/HalfbandKernel.h
  generate_halfband.py --check Source/DSP/Render/HalfbandKernel.h
"""

import argparse
import math
import sys

HALF_LENGTH = 33         # taps either side of the centre
TAPS = 2 * HALF_LENGTH + 1
BETA = 10.0


def bessel_i0(x):
    total, term, k = 1.0, 1.0, 1
    while True:
        term *= (x / (2.0 * k)) ** 2
        total += term
        if term < 1e-17 * total:
            return total
        k += 1


def tap(k):
    """Tap k samples from the centre: sinc at a quarter of the input rate."""
    if k == 0:
        return 0.5
    if k % 2 == 0:
        return 0.0
    sinc = math.sin(math.pi * k / 2.0) / (math.pi * k)
    window = bessel_i0(BETA * math.sqrt(1.0 - (k / (HALF_LENGTH + 1)) ** 2)) / bessel_i0(BETA)
    return sinc * window


def side_taps():
    """The odd taps right of the centre, scaled so the DC gain is exactly 1."""
    odd = [tap(k) for k in range(1, HALF_LENGTH + 1, 2)]
    scale = 0.5 / (2.0 * sum(odd))
    return [v * scale for v in odd]


def header():
    lines = [
        "#pragma once",
        "",
        "// Generated by Tools/generate_halfband.py; do not edit. The 2:1 stage of",
        f"// Render/Decimator.h: a {TAPS}-tap Kaiser-windowed halfband (beta {BETA}),",
        "// cutoff a quarter of the stage's input rate. The centre tap is 0.5 and",
        "// every other tap is 0, so only the odd taps right of the centre are",
        "// listed, nearest first; they sum to 0.25, for a DC gain of exactly 1.",
        "",
        "namespace protocodus::reboot::halfband {",
        "",
        f"constexpr int kHalfLength = {HALF_LENGTH};",
        f"constexpr int kSideTaps = {len(side_taps())};",
        "",
        "constexpr double kSide[kSideTaps] = {",
    ]
    for v in side_taps():
        lines.append(f"    {v!r},")
    lines += ["};", "", "} // namespace protocodus::reboot::halfband", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", metavar="PATH")
    group.add_argument("--check", metavar="PATH")
    args = parser.parse_args()
    text = header()
    if args.write:
        with open(args.write, "w", newline="\n") as f:
            f.write(text)
        return 0
    with open(args.check, newline="") as f:
        if f.read() != text:
            print(f"{args.check} differs from what Tools/generate_halfband.py writes", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
